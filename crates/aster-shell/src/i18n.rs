    /// The `{name}` markers in a template, sorted.
    fn markers(text: &str) -> Vec<&str> {
        let mut found = Vec::new();
        let mut rest = text;
        while let Some(start) = rest.find('{') {
            let end = start + rest[start..].find('}').expect("unclosed marker");
            found.push(&rest[start..=end]);
            rest = &rest[end + 1..];
        }
        found.sort_unstable();
        found
    }

    #[test]
    fn built_in_style_names_are_shown_in_the_interface_language() {
        let zh = Language::ZhHans.strings();
        assert_eq!(zh.style_name("Normal").as_deref(), Some("正文"));
        assert_eq!(zh.style_name("heading 3").as_deref(), Some("标题 3"));
        assert_eq!(zh.style_name("Heading 9").as_deref(), Some("标题 9"));
        assert_eq!(zh.style_name("List Paragraph").as_deref(), Some("列表段落"));
        let de = Language::De.strings();
        assert_eq!(de.style_name("heading 1").as_deref(), Some("Überschrift 1"));
        assert_eq!(de.style_name("footer").as_deref(), Some("Fußzeile"));
        // A custom name, or a heading beyond the ninth, stays as the file has it.
        assert_eq!(zh.style_name("My Style"), None);
        assert_eq!(zh.style_name("heading 10"), None);
        assert_eq!(zh.style_name("heading"), None);
    }

    #[test]
    fn no_language_has_empty_text() {
        for language in Language::ALL {
            for (name, text) in language.strings().fields() {
                assert!(!text.trim().is_empty(), "{language:?} {name} is empty");
            }
        }
    }

    #[test]
    fn every_language_uses_the_same_markers() {
        let reference = Language::ZhHans.strings().fields();
        for language in Language::ALL {
            for ((name, text), (_, expected)) in
                language.strings().fields().into_iter().zip(&reference)
            {
                assert_eq!(markers(text), markers(expected), "{language:?} {name}");
            }
        }
    }

    #[test]
    fn translations_are_not_copies_of_english() {
        // Product names and format names are the same everywhere; the rest is not.
        // "Important" and "Image" are the same words in French, "Format"
        // in French and German, "Link" in German.
        let shared = [
            "markdown_label",
            "pdf_label",
            "button_ok",
            "callout_important",
            "menu_format",
            "format_image",
            "format_link",
            // The same word in French and German.
            "number_date",
            "number_text",
            // "Rectangle" in French too.
            "shape_rect",
            // The same word in English and French.
            "comment_title",
            // "Name" in German.
            "formula_hint_name",
            // "Normal" in French and Spanish.
            "docstyle_normal",
        ];
        let english = EN.fields();
        for language in Language::ALL {
            if language == Language::En {
                continue;
            }
            for ((name, text), (_, source)) in language.strings().fields().into_iter().zip(&english)
            {
                if !shared.contains(&name) {
                    assert_ne!(text, *source, "{language:?} {name} is not translated");
                }
            }
        }
    }

