//! Interface text in every language the shell speaks.
//!
//! All wording the shell shows is a field of [`Strings`]; no other module and no
//! `.slint` file holds interface text. A language is one constant of that type,
//! so a missing translation does not compile, and switching language is just
//! handing the UI a different constant. Names of the editors (Writer, Sheets,
//! ...) are product names and are not translated.
//!
//! Text with a variable part marks it as `{name}`; [`fill`] puts the value in.

use crate::stats::ImeState;
use crate::tabs::DocKind;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Language {
    ZhHans,
    ZhHant,
    Ja,
    En,
    Fr,
    De,
    Es,
    Ko,
}

impl Language {
    /// In the order the language menu lists them.
    pub const ALL: [Language; 8] = [
        Language::ZhHans,
        Language::ZhHant,
        Language::Ja,
        Language::En,
        Language::Fr,
        Language::De,
        Language::Es,
        Language::Ko,
    ];

    /// Stable index, used to hand the language to the UI layer and back.
    pub fn index(self) -> usize {
        Self::ALL
            .iter()
            .position(|language| *language == self)
            .expect("ALL lists every language")
    }

    pub fn from_index(index: usize) -> Option<Self> {
        Self::ALL.get(index).copied()
    }

    /// BCP 47 tag.
    pub fn tag(self) -> &'static str {
        match self {
            Language::ZhHans => "zh-Hans",
            Language::ZhHant => "zh-Hant",
            Language::Ja => "ja",
            Language::En => "en",
            Language::Fr => "fr",
            Language::De => "de",
            Language::Es => "es",
            Language::Ko => "ko",
        }
    }

    /// The language's own name, shown in the language menu whatever the
    /// current language is.
    pub fn native_name(self) -> &'static str {
        match self {
            Language::ZhHans => "简体中文",
            Language::ZhHant => "繁體中文",
            Language::Ja => "日本語",
            Language::En => "English",
            Language::Fr => "Français",
            Language::De => "Deutsch",
            Language::Es => "Español",
            Language::Ko => "한국어",
        }
    }

    /// Pick a language from a tag such as `ja`, `ja-JP`, `zh_CN.UTF-8`,
    /// `zh-Hant-HK` or `en-US`. Chinese is Traditional when the tag names the
    /// Traditional script or a region that writes it, Simplified otherwise.
    pub fn from_tag(tag: &str) -> Option<Self> {
        let tag = tag.to_ascii_lowercase();
        let mut parts = tag.split(['-', '_', '.']);
        let primary = parts.next().unwrap_or_default();
        match primary {
            "zh" => {
                // An explicit script wins over the region: zh-Hans-HK is Simplified.
                let parts: Vec<&str> = parts.collect();
                let traditional = if parts.contains(&"hans") {
                    false
                } else {
                    parts
                        .iter()
                        .any(|part| matches!(*part, "hant" | "tw" | "hk" | "mo"))
                };
                Some(if traditional {
                    Language::ZhHant
                } else {
                    Language::ZhHans
                })
            }
            "ja" => Some(Language::Ja),
            "en" => Some(Language::En),
            "fr" => Some(Language::Fr),
            "de" => Some(Language::De),
            "es" => Some(Language::Es),
            "ko" => Some(Language::Ko),
            _ => None,
        }
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Language::ZhHans => &ZH_HANS,
            Language::ZhHant => &ZH_HANT,
            Language::Ja => &JA,
            Language::En => &EN,
            Language::Fr => &FR,
            Language::De => &DE,
            Language::Es => &ES,
            Language::Ko => &KO,
        }
    }
}

/// Replace `{name}` in a template with a value.
pub fn fill(template: &str, name: &str, value: &str) -> String {
    template.replace(&format!("{{{name}}}"), value)
}

macro_rules! strings {
    ($($(#[$doc:meta])* $field:ident,)+) => {
        /// Every piece of interface text, in one language.
        #[derive(Debug, PartialEq, Eq)]
        pub struct Strings {
            $($(#[$doc])* pub $field: &'static str,)+
        }

        impl Strings {
    /// The name Word shows for a built-in paragraph style, given the name a
    /// file stores (English, any case). None for any other name.
    pub fn style_name(&self, name: &str) -> Option<String> {
        let lower = name.trim().to_lowercase();
        if let Some(level) = lower.strip_prefix("heading ") {
            return match level.parse::<u8>() {
                Ok(level @ 1..=9) => Some(fill(self.heading_level, "level", &level.to_string())),
                _ => None,
            };
        }
        let shown = match lower.as_str() {
            "normal" => self.docstyle_normal,
            "title" => self.docstyle_title,
            "subtitle" => self.docstyle_subtitle,
            "list paragraph" => self.docstyle_list_paragraph,
            "quote" => self.docstyle_quote,
            "intense quote" => self.docstyle_intense_quote,
            "caption" => self.docstyle_caption,
            "no spacing" => self.docstyle_no_spacing,
            "header" => self.docstyle_header,
            "footer" => self.docstyle_footer,
            _ => return None,
        };
        Some(shown.to_owned())
    }

            /// Field names with their text, for checks that must cover all of them.
            pub fn fields(&self) -> Vec<(&'static str, &'static str)> {
                vec![$((stringify!($field), self.$field),)+]
            }
        }
    };
}

